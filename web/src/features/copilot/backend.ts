/* ===========================================================================
   助手后端开关（唯一口径）。

   `VITE_AGENT_BACKEND=dsh` 时助手走真后端（POST /api/agent/stream → DeepSeek）；
   缺省或 mock 时回落本地脚本回放。做成环境开关而不是写死，是为了一键回退：
   演示截图与联调互不干扰，改 .env 重启 vite 即可切换。

   ⚠️ **必须全站共用这一个常量**。此前这个判断写在 `copilot/index.tsx` 里是模块内
   `const`，只有流程页读它；知识库页的助手自己硬编码走回放，导致「流程页通了真模型、
   知识库页还在演示态」——同一语义两套判据，是本项目反复栽过的坑（占位/待确认口径、
   artifact_kind 枚举都栽过）。所以抽到这里，任何要用助手后端的地方都 import 它。
   =========================================================================== */

/** true = 走真后端（dsh）；false = 本地脚本回放。 */
export const USE_DSH = (import.meta.env.VITE_AGENT_BACKEND ?? 'mock').toLowerCase() === 'dsh'
