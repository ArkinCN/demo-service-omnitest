/**
 * 界面文案的简体归一化。
 *
 * 场景包的源材料（客户工程 Customer.h、报告模板 xlsm）里大量字段名是繁体，
 * 照抄进界面会出现简繁混排。口径：
 *   - 界面自己的标签、卡名、表单标签一律走 `simp()` 归一成简体；
 *   - 模板原文只在「报告预览」的纸面里按原样呈现，并在纸面上标「模板原文」。
 * 不做全量繁简转换，只收本仓两个场景包里实际出现过的字与词，避免误伤。
 */

/** 逐字映射：只收本仓源材料里实际出现过的繁体字 */
const CHAR: Record<string, string> = {
  韌: '韧', 體: '体', 戶: '户', 稱: '称', 聯: '联', 繫: '系', 電: '电', 話: '话',
  產: '产', 機: '机', 參: '参', 數: '数', 轉: '转', 頭: '头', 師: '师', 標: '标',
  準: '准', 壓: '压', 動: '动', 檔: '档', 設: '设', 計: '计', 圖: '图', 線: '线',
  測: '测', 過: '过', 應: '应', 實: '实', 顯: '显', 時: '时', 間: '间', 頻: '频',
  響: '响', 別: '别', 類: '类', 開: '开', 關: '关', 現: '现', 場: '场', 檢: '检',
  驅: '驱', 訊: '讯', 號: '号', 極: '极', 對: '对', 溫: '温', 錄: '录', 態: '态',
  無: '无', 這: '这', 個: '个', 級: '级', 總: '总', 內: '内',
}

/** 整词映射：不是简繁差异、而是术语口径差异的，统一到行业通用写法 */
const TERM: [RegExp, string][] = [
  [/韧体版本/g, '固件版本'],
  [/韧体/g, '固件'],
]

/** 把源材料里的繁体字段名归一成简体界面文案 */
export function simp(s: string): string {
  if (!s) return s
  let out = ''
  for (const ch of s) out += CHAR[ch] ?? ch
  for (const [re, to] of TERM) out = out.replace(re, to)
  return out
}
