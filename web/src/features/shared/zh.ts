/** 整词映射：不是简繁差异、而是术语口径差异的，统一到行业通用写法 */
const TERM: [RegExp, string][] = [
  [/韧体版本/g, '固件版本'],
  [/韧体/g, '固件'],
]

/** 把源材料里的繁体字段名归一成简体界面文案 */
export function simp(s: string): string {
  if (!s) return s
  let out = ''
  for (const ch of s) out += CHAR[ch] ?? ch
  for (const [re, to] of TERM) out = out.replace(re, to)
  return out
}
